def _rewrite_data_type_vocabulary() -> None:
    """Rename the data_type tokens on the two pre-existing config tables, and add `unit`."""
    for table in _CONFIG_TABLES:
        op.add_column(table, sa.Column(
            "unit", sa.String(20), nullable=True,
            comment="number 欄位的單位，例如 cm、mm；其他型別為 NULL",
        ))
        for old, new in _DATA_TYPE_MAP.items():
            op.execute(
                f"UPDATE {table} SET data_type = '{new}' WHERE data_type = '{old}'"  # noqa: S608
            )


