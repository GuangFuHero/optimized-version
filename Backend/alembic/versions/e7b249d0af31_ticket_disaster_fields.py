def downgrade() -> None:
    """Reverse everything, in the mirror order."""
    for table in reversed(_FEATURE_018_AUDITED_TABLES):
        op.execute(f"DROP TRIGGER IF EXISTS audit_trigger_{table} ON {table};")

    # Must come before the _DATA_TYPE_MAP_INVERSE rewrite below: restoring 'Enum' / 'Array'
    # violates a CHECK that only allows the new tokens, so dropping it first is not tidiness.
    for table in _ALL_CONFIG_TABLES:
        op.execute(f"ALTER TABLE {table} DROP CONSTRAINT IF EXISTS ck_{table}_data_type;")

    for column in (
        "landmark_note", "access_status", "victim_space", "space_description",
        "building_section",
    ):
        op.drop_column("secondary_locations", column)

    op.drop_column("tickets", "immediate_danger_reported")
    op.drop_column("tickets", "person_trapped_reported")
    op.add_column("tickets", sa.Column("disaster_type", sa.String(50), nullable=True))
    # Lossy by nature: a two-disaster ticket cannot fit in a scalar, so it keeps its first
    # type. Recorded rather than hidden — the array is the reason this column went away.
    op.execute(
        "UPDATE tickets SET disaster_type = disaster_types[1]"
        " WHERE cardinality(disaster_types) > 0"
    )
    op.drop_column("tickets", "disaster_types")

    op.drop_index("ix_ticket_disaster_details_ticket_uuid", table_name="ticket_disaster_details")
    op.drop_table("ticket_disaster_details")
    op.drop_table("ticket_property_config")

    for table in _CONFIG_TABLES:
        for new, old in _DATA_TYPE_MAP_INVERSE.items():
            op.execute(
                f"UPDATE {table} SET data_type = '{old}' WHERE data_type = '{new}'"  # noqa: S608
            )
        op.drop_column(table, "unit")

    op.drop_table("disaster_types")
